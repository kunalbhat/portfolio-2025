export const GLYPH_H = 5;

export function textWidth(text: string, spacing = 1): number {
  let w = 0;
  for (const ch of text.toUpperCase()) w += (GLYPHS[ch] ?? GLYPHS[' '])[0].length + spacing;
  return Math.max(0, w - spacing);
}

/** Draw text with its top-left at (x, y). Returns the width drawn. */
export function drawText(bm: Bitmap, text: string, x: number, y: number, c: Color, spacing = 1): number {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const g = GLYPHS[ch] ?? GLYPHS[' '];
    g.forEach((row, j) => {
      for (let i = 0; i < row.length; i++) if (row[i] === '#') bm.px(cx + i, y + j, c);
    });
    cx += g[0].length + spacing;
  }
  return cx - x - spacing;
}

export function drawTextCentered(bm: Bitmap, text: string, cx: number, y: number, c: Color, spacing = 1) {
  return drawText(bm, text, Math.round(cx - textWidth(text, spacing) / 2), y, c, spacing);
}
